// Leccion 2: Perfil de red social
// Variables con los tipos String, int, double y boolean.

public class Main {
    public static void main(String[] args) {
        // Cada variable es una caja con tipo, nombre y valor
        String usuario = "Ana";          // texto, entre comillas
        int seguidores = 1250;           // numero entero, sin comillas
        double promedioLikes = 87.5;     // numero con decimales, con punto
        boolean verificada = true;       // verdadero o falso

        // El texto fijo va entre comillas; la variable, sin comillas
        System.out.println("Usuario: " + usuario);
        System.out.println("Seguidores: " + seguidores);
        System.out.println("Promedio de likes: " + promedioLikes);
        System.out.println("Es verificada?: " + verificada);
    }
}
